import asyncio, time
from playwright.async_api import async_playwright
U = "http://localhost:8765/"; OUT = "screenshots/v2/"
async def brand(b):
    pg = await b.new_page(device_scale_factor=4, viewport={"width": 368, "height": 80})
    await pg.goto(U + "static/brand/logo.svg"); await pg.screenshot(path="brand/logo.png", omit_background=True, clip={"x":0,"y":0,"width":360,"height":72})
    pg2 = await b.new_page(device_scale_factor=8, viewport={"width": 64, "height": 64})
    await pg2.goto(U + "static/brand/mark.svg"); await pg2.screenshot(path="brand/mark-512.png", omit_background=True)
    pg4 = await b.new_page(device_scale_factor=4, viewport={"width": 392, "height": 104})
    await pg4.set_content('<body style="margin:0;background:#05070D;padding:16px"><img src="%sstatic/brand/logo.svg" width="360" height="72"></body>' % U)
    await pg4.wait_for_timeout(500); await pg4.screenshot(path="brand/logo-on-dark.png")
    pg3 = await b.new_page(device_scale_factor=0.5, viewport={"width": 64, "height": 64})
    await pg3.goto(U + "static/brand/mark.svg"); await pg3.screenshot(path="brand/favicon-32.png", omit_background=True)
