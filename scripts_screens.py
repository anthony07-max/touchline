import asyncio, time
from playwright.async_api import async_playwright
U = "http://localhost:8765/"
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pg = await b.new_page(viewport={"width": 1500, "height": 1000})
        errs = []
        pg.on("pageerror", lambda e: errs.append(str(e)))
        pg.on("console", lambda m: m.type == "error" and errs.append(m.text))
        await pg.goto(U); await pg.wait_for_timeout(1200)
        await pg.click("nav button[data-t=account]")
        await pg.fill("#em", f"demo{int(time.time())}@example.com"); await pg.fill("#pw", "demo-password-1")
        await pg.click("#tab-account button:has-text(\"Register\")"); await pg.wait_for_timeout(800)
        tok = await pg.evaluate("TOKEN")
        await pg.evaluate("fetch('/api/billing/dev-upgrade',{method:'POST',headers:{Authorization:'Bearer '+TOKEN}})")
        await pg.click("nav button[data-t=match]"); await pg.wait_for_timeout(500)
        await pg.select_option("#t_pressing", "high"); await pg.select_option("#t_defensive_line", "high")
        await pg.click("#simBtn"); await pg.wait_for_selector("#out .hyp"); await pg.wait_for_timeout(400)
        await pg.screenshot(path="screenshots/01_match_simulation.png", full_page=True)
        await pg.fill("#scName", "High press + high line"); await pg.click("#tab-match button:has-text(\"Save\")"); await pg.wait_for_timeout(600)
        await pg.click("nav button[data-t=copilot]")
        await pg.fill("#q", "How do I exploit the space behind their defence?")
        await pg.click("text=Ask copilot"); await pg.wait_for_selector("#cop .hyp", timeout=30000)
        await pg.click("text=SIMULATE AI RECOMMENDATION"); await pg.wait_for_selector("#copSim .hyp", timeout=30000)
        await pg.screenshot(path="screenshots/02_copilot.png", full_page=True)
        await pg.click("#copSim >> text=Accept"); await pg.wait_for_timeout(300)
        await pg.fill("#scName", "AI recommendation"); await pg.click("#tab-match button:has-text(\"Save\")"); await pg.wait_for_timeout(600)
        await pg.click("nav button[data-t=replay]"); await pg.wait_for_timeout(300)
        await pg.click("#rpPlay"); await pg.wait_for_timeout(2500); await pg.click("#rpPlay")
        await pg.screenshot(path="screenshots/03_replay_alternate.png", full_page=True)
        await pg.click("#rpReal"); await pg.evaluate("rpSeek(505)")
        await pg.screenshot(path="screenshots/04_replay_real.png", full_page=True)
        await pg.click("nav button[data-t=lab]"); await pg.wait_for_timeout(600)
        await pg.click("text=Compare selected"); await pg.wait_for_timeout(600)
        await pg.screenshot(path="screenshots/05_scenario_lab.png", full_page=True)
        await pg.click("nav button[data-t=play]"); await pg.wait_for_timeout(800)
        await pg.fill("#lgName", "Sunday Tacticians"); await pg.click("#tab-play button:has-text(\"Create\")"); await pg.wait_for_timeout(600)
        await pg.click("text=Submit decision"); await pg.wait_for_selector("#chRes .hyp", timeout=30000); await pg.wait_for_timeout(800)
        await pg.screenshot(path="screenshots/06_challenge_leagues.png", full_page=True)
        await pg.click("nav button[data-t=autopsy]"); await pg.wait_for_timeout(2500)
        await pg.screenshot(path="screenshots/07_autopsy.png", full_page=True)
        await pg.click("nav button[data-t=account]"); await pg.wait_for_timeout(600); await pg.click("text=Upgrade to Pro"); await pg.wait_for_timeout(400)
        await pg.screenshot(path="screenshots/08_account_plans.png", full_page=True)
        print("ERRORS:", errs)
        await b.close()
asyncio.run(main())
